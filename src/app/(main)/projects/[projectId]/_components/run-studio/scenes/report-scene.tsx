"use client";

import { Fragment, useRef } from "react";

import { AlertTriangle, X } from "lucide-react";
import { motion } from "motion/react";

import type { ReportContent } from "@/lib/run-stream/run-state";
import { signed } from "@/lib/run-stream/selectors";

import { FigureCard } from "../figures";
import { AgentCursor, VerdictBadge } from "../run-bits";
import { useReveal } from "../workspace-context";
import { Placeholder } from "./scene-ui";

export function ReportScene({
  data,
  runLabel,
  rounds,
  live,
}: {
  data: ReportContent;
  runLabel: string;
  rounds: number;
  live: boolean;
}) {
  const scene = useRef<HTMLDivElement>(null);
  const figuresRef = useRef<HTMLDivElement>(null);
  const reproRef = useRef<HTMLDivElement>(null);
  useReveal(figuresRef, data.figures.length, live);
  useReveal(reproRef, data.repro.length, live);
  const noted = Object.keys(data.notes);

  let target: string | null = data.rows.length ? `report:${data.rows[data.rows.length - 1].hypothesis_id}` : null;
  let role: "code" | "interpreter" = "code";
  if (noted.length) {
    target = `note:${noted[noted.length - 1]}`;
    role = "interpreter";
  }

  return (
    <div ref={scene} className="relative flex flex-col gap-6">
      <header className="flex flex-wrap items-end justify-between gap-4 rounded-xl bg-card px-4.5 py-4 ring-1 ring-foreground/10">
        <div>
          <span className="font-medium text-muted-foreground text-xs uppercase tracking-wide">
            Research report · generated by code
          </span>
          <h3 className="mt-1 font-semibold text-lg tracking-tight">{runLabel} · Sleep and exam scores</h3>
        </div>
        <dl className="flex flex-wrap gap-6">
          {[
            ["Data", "student_wellbeing v2"],
            ["Rounds", String(rounds)],
            ["Source", "results.json"],
          ].map(([k, v]) => (
            <div key={k}>
              <dt className="text-muted-foreground text-xs">{k}</dt>
              <dd className="font-mono text-xs">{v}</dd>
            </div>
          ))}
        </dl>
      </header>

      <section>
        <h4 className="mb-2.5 flex items-baseline gap-2.5 font-semibold text-sm">
          1 · Every result
          <span className="font-mono font-normal text-muted-foreground text-xs">{data.rows.length} rows</span>
        </h4>
        <div className="overflow-x-auto rounded-xl bg-card ring-1 ring-foreground/10">
          <table className="w-full text-xs">
            <thead className="bg-muted/50 text-muted-foreground">
              <tr>
                {["ID", "Hypothesis", "Round", "Estimate", "95% range", "Verdict", "What it means", "Source"].map(
                  (h) => (
                    <th key={h} className="whitespace-nowrap px-3 py-2 text-left font-medium">
                      {h}
                    </th>
                  ),
                )}
              </tr>
            </thead>
            <tbody>
              {data.rows.map((row) => {
                const note = data.notes[row.hypothesis_id];
                return (
                  <motion.tr
                    key={row.hypothesis_id}
                    data-cursor={`report:${row.hypothesis_id}`}
                    initial={{ opacity: 0, y: 6 }}
                    animate={{ opacity: 1, y: 0 }}
                    className="border-t align-top"
                  >
                    <td className="px-3 py-2.5">
                      <span
                        className={
                          row.status === "dropped"
                            ? "rounded-md bg-muted px-1.5 py-0.5 font-mono font-semibold"
                            : "rounded-md bg-primary px-1.5 py-0.5 font-mono font-semibold text-primary-foreground"
                        }
                      >
                        {row.hypothesis_id}
                      </span>
                    </td>
                    <td className={row.status === "dropped" ? "px-3 py-2.5 text-muted-foreground" : "px-3 py-2.5"}>
                      {row.statement}
                    </td>
                    <td className="px-3 py-2.5 font-mono">{row.round ? `R${row.round}` : "—"}</td>
                    {row.status === "result" &&
                    row.estimate !== undefined &&
                    row.ci_low !== undefined &&
                    row.ci_high !== undefined ? (
                      <>
                        <td className="px-3 py-2.5 font-mono">{signed(row.estimate)}</td>
                        <td className="whitespace-nowrap px-3 py-2.5 font-mono text-muted-foreground">
                          {signed(row.ci_low)} to {signed(row.ci_high)}
                        </td>
                        <td className="px-3 py-2.5">{row.verdict && <VerdictBadge verdict={row.verdict} />}</td>
                      </>
                    ) : (
                      <td colSpan={3} className="px-3 py-2.5">
                        {row.status === "crashed" ? (
                          <span className="inline-flex h-5 items-center gap-1 rounded-full bg-rose-500/12 px-2 font-medium text-rose-700 dark:text-rose-300">
                            <X className="size-3" />
                            Never ran
                          </span>
                        ) : (
                          <span className="inline-flex h-5 items-center rounded-full bg-muted px-2 font-medium">
                            Dropped by you
                          </span>
                        )}
                      </td>
                    )}
                    <td data-cursor={`note:${row.hypothesis_id}`} className="min-w-56 px-3 py-2.5">
                      {note ? (
                        <motion.span initial={{ opacity: 0 }} animate={{ opacity: 1 }} className="block">
                          {note.note}
                          {note.objection && (
                            <span className="mt-1 flex items-start gap-1.5 text-orange-700 dark:text-orange-300">
                              <AlertTriangle className="mt-px size-3 shrink-0" />
                              Skeptic: {note.objection}
                            </span>
                          )}
                        </motion.span>
                      ) : (
                        <span className="text-muted-foreground">—</span>
                      )}
                    </td>
                    <td className="whitespace-nowrap px-3 py-2.5 font-mono text-[11px] text-muted-foreground">
                      {row.result_key ?? "—"}
                    </td>
                  </motion.tr>
                );
              })}
            </tbody>
          </table>
        </div>
      </section>

      <section ref={figuresRef}>
        <h4 className="mb-2.5 font-semibold text-sm">2 · Figures</h4>
        <div className="grid gap-3.5 md:grid-cols-2 xl:grid-cols-3">
          {[1, 2, 3].map((n) => {
            const figure = data.figures.find((f) => f.id === n);
            return figure ? (
              <FigureCard key={n} figure={figure} />
            ) : (
              <Placeholder key={n} className="min-h-56">
                Figure {n}
              </Placeholder>
            );
          })}
        </div>
      </section>

      <section ref={reproRef}>
        <h4 className="mb-2.5 font-semibold text-sm">3 · How to reproduce it</h4>
        {data.repro.length ? (
          <dl className="grid grid-cols-1 border-t text-sm sm:grid-cols-[160px_minmax(0,1fr)]">
            {data.repro.map((item, i) => (
              <Fragment key={item.label}>
                <motion.dt
                  initial={{ opacity: 0 }}
                  animate={{ opacity: 1 }}
                  transition={{ delay: i * 0.1 }}
                  className="border-b py-2.5 text-muted-foreground max-sm:border-b-0 max-sm:pb-0"
                >
                  {item.label}
                </motion.dt>
                <motion.dd
                  initial={{ opacity: 0, x: -4 }}
                  animate={{ opacity: 1, x: 0 }}
                  transition={{ delay: i * 0.1 }}
                  className="whitespace-pre-line border-b py-2.5 font-mono text-xs leading-relaxed"
                >
                  {item.value}
                </motion.dd>
              </Fragment>
            ))}
          </dl>
        ) : (
          <Placeholder>Written last</Placeholder>
        )}
      </section>
      <AgentCursor
        agent={live ? role : null}
        container={scene}
        target={target}
        version={`${data.rows.length}-${noted.length}`}
      />
    </div>
  );
}
